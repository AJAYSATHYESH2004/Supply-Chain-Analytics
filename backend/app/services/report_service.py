import pandas as pd
from sqlalchemy.orm import Session
from sqlalchemy import func
from io import BytesIO
from app.models import models
from fpdf import FPDF

class ReportPDF(FPDF):
    def header(self):
        # Emerald theme banner
        self.set_fill_color(16, 185, 129)
        self.set_text_color(255, 255, 255)
        self.set_font("helvetica", "B", 14)
        self.cell(0, 15, "  SmartChain AI - Enterprise Operations Ledger", fill=True, ln=True, align="L")
        self.ln(5)
        
    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by SmartChain AI Governance Center", align="C")

def df_to_pdf(df, title):
    pdf = ReportPDF()
    pdf.add_page()
    pdf.set_font("helvetica", "B", 12)
    pdf.set_text_color(31, 41, 55)
    pdf.cell(0, 10, title, ln=True)
    pdf.ln(5)
    
    # Table headers
    pdf.set_font("helvetica", "B", 8)
    pdf.set_fill_color(243, 244, 246)
    pdf.set_text_color(75, 85, 99)
    
    cols = list(df.columns)
    col_width = 190 / max(len(cols), 1)
    
    for col in cols:
        pdf.cell(col_width, 8, str(col), border=1, fill=True, align="C")
    pdf.ln()
    
    # Table rows
    pdf.set_font("helvetica", "", 8)
    pdf.set_text_color(31, 41, 55)
    for idx, row in df.iterrows():
        for col in cols:
            val = str(row[col])
            if len(val) > 22:
                val = val[:19] + "..."
            pdf.cell(col_width, 8, val, border=1, align="C")
        pdf.ln()
        
    return pdf.output()

def df_to_format(df, format: str, title: str):
    if format == "csv":
        return df.to_csv(index=False).encode('utf-8')
    elif format == "excel":
        output = BytesIO()
        with pd.ExcelWriter(output, engine='openpyxl') as writer:
            df.to_excel(writer, index=False)
        return output.getvalue()
    elif format == "pdf":
        return df_to_pdf(df, title)
    return None

class ReportService:
    @staticmethod
    def generate_inventory_report(db: Session, format: str = "csv"):
        products = db.query(models.Product).all()
        data = []
        for p in products:
            data.append({
                "ID": p.id,
                "Name": p.name,
                "Category": p.category,
                "Current Stock": p.current_stock,
                "Reorder Level": p.reorder_level,
                "Price": p.price,
                "Created At": p.created_at.strftime("%Y-%m-%d") if p.created_at else "N/A"
            })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["ID", "Name", "Category", "Current Stock", "Reorder Level", "Price", "Created At"])
        return df_to_format(df, format, "Inventory Ledger Report")

    @staticmethod
    def generate_sales_report(db: Session, format: str = "csv"):
        sales = db.query(models.Sale).all()
        data = []
        for s in sales:
            data.append({
                "Sale ID": s.id,
                "Product ID": s.product_id,
                "Quantity": s.quantity,
                "Total Amount": s.total_amount,
                "Sale Date": s.sale_date.strftime("%Y-%m-%d %H:%M") if s.sale_date else "N/A"
            })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Sale ID", "Product ID", "Quantity", "Total Amount", "Sale Date"])
        return df_to_format(df, format, "Sales and Invoice Report")

    @staticmethod
    def generate_inventory_utilization_report(db: Session, format: str = "csv"):
        depots = db.query(models.Depot).all()
        data = []
        for d in depots:
            total_stock = db.query(func.sum(models.Inventory.current_stock)).filter(models.Inventory.depot_id == d.id).scalar() or 0
            utilization = round((total_stock / d.capacity) * 100, 2) if d.capacity > 0 else 0
            state_name = d.state.name if d.state else "Unknown"
            data.append({
                "Depot ID": d.id,
                "Depot Name": d.name,
                "State": state_name,
                "Capacity": d.capacity,
                "Current Stock": total_stock,
                "Utilization %": utilization
            })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Depot ID", "Depot Name", "State", "Capacity", "Current Stock", "Utilization %"])
        return df_to_format(df, format, "Inventory Capacity Utilization Report")

    @staticmethod
    def generate_surplus_inventory_report(db: Session, format: str = "csv"):
        items = db.query(models.Inventory).all()
        data = []
        for inv in items:
            required = inv.reorder_level
            if inv.current_stock > required:
                surplus = inv.current_stock - required
                data.append({
                    "Depot": inv.depot.name if inv.depot else f"Depot #{inv.depot_id}",
                    "Product": inv.product.name if inv.product else f"Prod #{inv.product_id}",
                    "Category": inv.product.category if inv.product else "N/A",
                    "Current Stock": inv.current_stock,
                    "Reorder Level": inv.reorder_level,
                    "Surplus Qty": surplus
                })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Depot", "Product", "Category", "Current Stock", "Reorder Level", "Surplus Qty"])
        return df_to_format(df, format, "Surplus Stock Inventory Report")

    @staticmethod
    def generate_deficit_inventory_report(db: Session, format: str = "csv"):
        items = db.query(models.Inventory).all()
        data = []
        for inv in items:
            required = inv.reorder_level
            if inv.current_stock < required:
                deficit = required - inv.current_stock
                data.append({
                    "Depot": inv.depot.name if inv.depot else f"Depot #{inv.depot_id}",
                    "Product": inv.product.name if inv.product else f"Prod #{inv.product_id}",
                    "Category": inv.product.category if inv.product else "N/A",
                    "Current Stock": inv.current_stock,
                    "Reorder Level": inv.reorder_level,
                    "Deficit Qty": deficit
                })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Depot", "Product", "Category", "Current Stock", "Reorder Level", "Deficit Qty"])
        return df_to_format(df, format, "Deficit (Shortage) Inventory Report")

    @staticmethod
    def generate_transfer_recommendations_report(db: Session, format: str = "csv"):
        recs = db.query(models.TransferRecommendation).all()
        data = []
        for r in recs:
            data.append({
                "Rec ID": r.id,
                "Source Depot": r.source_depot.name if r.source_depot else "Unknown",
                "Dest Depot": r.destination_depot.name if r.destination_depot else "Unknown",
                "Product": r.product.name if r.product else f"Prod #{r.product_id}",
                "Quantity": r.quantity,
                "Distance (KM)": r.distance_km,
                "Tariff Cost (INR)": r.transport_cost,
                "Match Score %": r.recommendation_score,
                "Status": r.status
            })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Rec ID", "Source Depot", "Dest Depot", "Product", "Quantity", "Distance (KM)", "Tariff Cost (INR)", "Match Score %", "Status"])
        return df_to_format(df, format, "Transfer Recommendation Optimization Report")

    @staticmethod
    def generate_production_avoidance_report(db: Session, format: str = "csv"):
        recs = db.query(models.ProductionRecommendation).all()
        data = []
        for r in recs:
            data.append({
                "Rec ID": r.id,
                "Depot Name": r.depot.name if r.depot else "Unknown",
                "Product": r.product.name if r.product else f"Prod #{r.product_id}",
                "Quantity": r.quantity,
                "Avoided Cost (INR)": r.production_cost,
                "Reason": r.reason,
                "Status": r.status
            })
        df = pd.DataFrame(data) if data else pd.DataFrame(columns=["Rec ID", "Depot Name", "Product", "Quantity", "Avoided Cost (INR)", "Reason", "Status"])
        return df_to_format(df, format, "Avoided Production Optimization Report")

    @staticmethod
    def generate_cost_savings_report(db: Session, format: str = "csv"):
        transfers = db.query(models.TransferRecommendation).all()
        avoided_prod = db.query(models.ProductionRecommendation).all()
        
        total_units_saved = sum(t.quantity for t in transfers if t.status == 'APPROVED')
        total_logistics_cost = sum(t.transport_cost for t in transfers if t.status == 'APPROVED')
        total_prod_avoided_cost = sum(p.production_cost for p in avoided_prod if p.status == 'APPROVED')
        
        net_savings = max(0.0, total_prod_avoided_cost - total_logistics_cost)
        
        data = [
            {"Avoided Metric": "Total Approved Avoided Units", "Value": str(total_units_saved)},
            {"Avoided Metric": "Avoided Production Value (INR)", "Value": f"INR {total_prod_avoided_cost:,.2f}"},
            {"Avoided Metric": "Approved Transport Logistics Tariff (INR)", "Value": f"INR {total_logistics_cost:,.2f}"},
            {"Avoided Metric": "Net Supply Chain Financial Savings (INR)", "Value": f"INR {net_savings:,.2f}"}
        ]
        df = pd.DataFrame(data)
        return df_to_format(df, format, "Avoided Cost and Net Savings Analytics Report")
