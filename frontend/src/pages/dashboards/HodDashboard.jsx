import React, { useState, useEffect } from 'react';
import { 
  CheckSquare, FileCheck, TrendingUp, IndianRupee, Cpu, ArrowRight, Activity, Loader2, Award 
} from 'lucide-react';
import { rebalancingAPI } from '../../services/api';
import TypewriterText from '../../components/TypewriterText';
import { useAuth } from '../../context/AuthContext';
import { useWebSocket } from '../../hooks/useWebSocket';

const StatCard = ({ title, value, icon: Icon, color, change }) => {
  const gradientStyles = {
    accent: "bg-gradient-to-br from-[#10b981]/8 via-card to-[#059669]/3 border-[#10b981]/15 text-[#0f766e] hover:border-[#10b981]/30 hover:shadow-lg",
    success: "bg-gradient-to-br from-[#3b82f6]/8 via-card to-[#1d4ed8]/3 border-[#3b82f6]/15 text-[#1d4ed8] hover:border-[#3b82f6]/30 hover:shadow-lg",
    warning: "bg-gradient-to-br from-[#f59e0b]/8 via-card to-[#d97706]/3 border-[#f59e0b]/15 text-[#d97706] hover:border-[#f59e0b]/30 hover:shadow-lg",
    primary: "bg-gradient-to-br from-[#ef4444]/8 via-card to-[#b91c1c]/3 border-[#ef4444]/15 text-[#b91c1c] hover:border-[#ef4444]/30 hover:shadow-lg"
  };

  const style = gradientStyles[color] || "bg-card border-border hover:shadow-xl text-foreground";

  return (
    <div className={`p-6 rounded-2xl border transition-all duration-300 hover:-translate-y-1.5 hover:scale-[1.02] group ${style}`}>
      <div className="flex justify-between items-start mb-4">
        <div className="p-3 rounded-xl bg-background/60 text-current transition-colors shadow-sm">
          <Icon size={24} />
        </div>
        {change && (
          <div className="text-[10px] font-black uppercase tracking-wider bg-background/40 px-2 py-0.5 rounded-full border border-border/20">
            {change}
          </div>
        )}
      </div>
      <p className="text-muted-foreground text-xs font-bold uppercase tracking-wider">{title}</p>
      <h3 className="text-2xl font-black mt-1 text-foreground">{value}</h3>
    </div>
  );
};

const HodDashboard = () => {
  const [summary, setSummary] = useState(null);
  const [loading, setLoading] = useState(true);

  const { user } = useAuth();

  // WebSocket hook for dashboard real-time updates
  useWebSocket('/ws/dashboard', (msg) => {
    if (msg.event === 'refresh_dashboard') {
      fetchSummary();
    }
  }, [user?.id]);

  useEffect(() => {
    fetchSummary();
  }, []);

  const fetchSummary = async () => {
    try {
      setLoading(true);
      const summData = await rebalancingAPI.getSummary();
      setSummary(summData);
      setLoading(false);
    } catch (err) {
      console.error(err);
      setLoading(false);
    }
  };

  return (
    <div className="space-y-8 animate-in fade-in duration-700">
      <div className="flex justify-between items-center">
        <div>
          <h1 className="text-3xl font-black tracking-tighter">
            <TypewriterText text="HOD Intelligence Hub" />
          </h1>
          <p className="text-muted-foreground font-medium mt-1">Strategic overview of avoided production costs, transfer optimizations, and overall supply chain savings.</p>
        </div>
        <div className="flex gap-2">
          <div className="flex items-center gap-2 px-4 py-2 bg-secondary rounded-xl text-xs font-bold border border-border">
            <Activity size={14} className="text-success" />
            ROLE: SUPPLY CHAIN HEAD
          </div>
        </div>
      </div>

      {loading ? (
        <div className="flex flex-col items-center justify-center py-20 gap-4">
          <Loader2 className="animate-spin text-primary" size={32} />
          <div className="text-muted-foreground font-medium">Fetching head office KPIs...</div>
        </div>
      ) : (
        <>
          {summary && (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
              <StatCard title="Avoided Production Costs" value={`₹${summary.production_cost_avoided.toLocaleString('en-IN')}`} icon={Cpu} color="accent" change="AI Saved" />
              <StatCard title="Transportation Tariffs" value={`₹${summary.logistics_cost.toLocaleString('en-IN')}`} icon={TrendingUp} color="warning" />
              <StatCard title="Net Logistics Savings" value={`₹${summary.net_savings.toLocaleString('en-IN')}`} icon={IndianRupee} color="success" change="ROI" />
              <StatCard title="Avoided Batches Count" value={summary.units_saved.toLocaleString()} icon={Award} color="primary" />
            </div>
          )}

          <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
            <div className="bg-card p-8 rounded-3xl border border-border shadow-sm space-y-6">
              <div>
                <h3 className="text-lg font-bold">Pending Recommendations Approvals</h3>
                <p className="text-xs text-muted-foreground mt-0.5">Recommendations generated by the optimization algorithm currently awaiting your authorization.</p>
              </div>
              
              {summary && (
                <div className="grid grid-cols-2 gap-4">
                  <a href="/transfer-recommendations" className="p-4 bg-secondary/30 rounded-2xl border border-border/50 hover:bg-secondary/50 transition-all block">
                    <p className="text-2xl font-black text-primary">{summary.pending_transfers_count}</p>
                    <p className="text-xs text-muted-foreground font-bold mt-1 uppercase">Pending Transfers</p>
                  </a>
                  <a href="/rebalancing" className="p-4 bg-secondary/30 rounded-2xl border border-border/50 hover:bg-secondary/50 transition-all block">
                    <p className="text-2xl font-black text-accent">{summary.pending_production_count}</p>
                    <p className="text-xs text-muted-foreground font-bold mt-1 uppercase">Pending Productions</p>
                  </a>
                </div>
              )}
            </div>

            <div className="bg-card p-8 rounded-3xl border border-border shadow-sm flex flex-col justify-start">
              <h3 className="text-lg font-bold mb-1">Operational Analytics Reports</h3>
              <p className="text-xs text-muted-foreground mb-6">Access strategic reports tracking net rebalancing metrics.</p>
              
              <div className="space-y-3">
                <a href="/reports" className="w-full flex items-center justify-between p-3.5 bg-secondary/25 border border-border/40 rounded-2xl hover:bg-secondary/40 transition-colors font-bold text-xs text-foreground">
                  View Inventory Utilization Report <ArrowRight size={14} />
                </a>
                <a href="/reports" className="w-full flex items-center justify-between p-3.5 bg-secondary/25 border border-border/40 rounded-2xl hover:bg-secondary/40 transition-colors font-bold text-xs text-foreground">
                  View Production Avoidance Report <ArrowRight size={14} />
                </a>
                <a href="/reports" className="w-full flex items-center justify-between p-3.5 bg-secondary/25 border border-border/40 rounded-2xl hover:bg-secondary/40 transition-colors font-bold text-xs text-foreground">
                  View Logistics Cost Savings Report <ArrowRight size={14} />
                </a>
              </div>
            </div>
          </div>
        </>
      )}
    </div>
  );
};

export default HodDashboard;
